export function registerIcons(icons) {
    Object.assign(ICONS, icons)
}

/**
 * `name` is a registered kebab-case name, or a lucide component passed directly.
 */
export function Icon({ name, className }) {
    const Glyph = (typeof name === 'string' ? ICONS[name] : name) ?? Circle

    return <Glyph className={cn('size-4 shrink-0', className)} />
}
